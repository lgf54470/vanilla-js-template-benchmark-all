#!/usr/bin/env -S deno run --allow-read --allow-write

const modulesDir = new URL("../apps/web/src/modules", import.meta.url).pathname;
const outputFile =
  new URL("../apps/web/src/shared/core/generated-module-registry.js", import.meta.url).pathname;

const modules = [];

try {
  for await (const entry of Deno.readDir(modulesDir)) {
    if (entry.isDirectory) {
      const jsonPath = `${modulesDir}/${entry.name}/module.json`;
      try {
        const text = await Deno.readTextFile(jsonPath);
        const meta = JSON.parse(text);
        modules.push({
          id: entry.name,
          ...meta,
          entryPath: `../../modules/${entry.name}/index.js`,
        });
      } catch {
        // Module.json not found or invalid
      }
    }
  }
} catch {
  // Modules directory does not exist yet
}

// Sort by order/sort_order
modules.sort((a, b) => (a.order ?? 99) - (b.order ?? 99));

const content = `// This file is auto-generated by scripts/generate-registry.js
export const MODULE_METAS = ${JSON.stringify(modules, null, 2)};
`;

await Deno.writeTextFile(outputFile, content);
console.log(`[generate-registry] Generated registry with ${modules.length} modules.`);
